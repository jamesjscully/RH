"""Export the late active-edge finite model for Julia autodiff.

This writes a small Julia include file with only the reduced data needed for
ForwardDiff/QuadGK experiments:

    scripts/numerics/julia/generated/active23_data.jl

The Python/Numpy witnesses remain the source of truth for constructing the
finite Sonin model.  Julia receives frozen matrices and differentiates the
reduced shell-direction formulas.

Run:
    python3 -m scripts.numerics.witness.prime_defect_export_julia_reduced
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from .prime_carleson_flow import _sym
from .prime_defect_active_atom_shift import active_state
from .prime_defect_riccati_storage import _blocks


OUT = Path("scripts/numerics/julia/generated/active23_data.jl")


def _julia_float(x: float) -> str:
    return f"{float(x):.17e}"


def _julia_vector(name: str, values: np.ndarray) -> str:
    vals = ", ".join(_julia_float(x) for x in np.asarray(values).ravel())
    return f"{name} = [{vals}]"


def _julia_matrix(name: str, values: np.ndarray) -> str:
    arr = np.asarray(values, dtype=float)
    rows = [
        " ".join(_julia_float(x) for x in row)
        for row in arr
    ]
    body = ";\n        ".join(rows)
    return f"{name} = [{body}]"


def reduced_data(ncenters: int = 25, half_width: float = 0.06) -> dict:
    state = active_state(ncenters, half_width)
    old_dim = state["old_dim"]
    A, C, D = _blocks(state["current"], old_dim)
    X = np.linalg.solve(A, C)
    S = _sym(D - C.T @ X)

    # Exact 23-cell Riccati matrices in the fixed old/shell splitting.
    # The actual atom block is reconstructed in Julia through q/K.  For the
    # Riccati update we export the matrices computed from Python's compressed
    # cell: smooth_block minus exact compressed atom.
    from .prime_defect_active_atom_shift import _compressed_atom_block

    atom_block = _compressed_atom_block(state, state["logn"], state["atom_weight"])
    cell = _sym(state["smooth_block"] - atom_block)
    E_A, E_C, E_D = _blocks(cell, old_dim)
    A_plus = _sym(A + E_A)
    residual = E_C - E_A @ X
    Q = _sym(E_D - X.T @ E_C - E_C.T @ X + X.T @ E_A @ X)
    square = _sym(residual.T @ np.linalg.solve(A_plus, residual))
    G = _sym(Q - square)

    shell_dim = S.shape[0]
    f_map = np.vstack([X, -np.eye(shell_dim)])
    coeff_map = state["B"] @ f_map
    lo, hi = state["cell"]
    edge = float(state["ambient"].centers.max() + state["ambient"].half_width)
    smooth_mass = 4.0 * (math.exp(0.5 * hi) - math.exp(0.5 * lo))
    eigs, vecs = np.linalg.eigh(S)
    active = vecs[:, 0]
    if active[0] < 0.0:
        active = -active
    return {
        "ncenters": ncenters,
        "half_width": state["half_width"],
        "centers": state["ambient"].centers,
        "edge": edge,
        "cell_lo": lo,
        "cell_hi": hi,
        "logn": state["logn"],
        "w_min": max(0.0, 2.0 * edge - hi),
        "w_max": max(0.0, 2.0 * edge - lo),
        "w_atom": max(0.0, 2.0 * edge - state["logn"]),
        "atom_weight": state["atom_weight"],
        "smooth_mass": smooth_mass,
        "old_dim": old_dim,
        "shell_dim": shell_dim,
        "coeff_map": coeff_map,
        "S": S,
        "Q": Q,
        "square": square,
        "G": G,
        "active_vec": active,
        "schur_eigs": eigs,
    }


def write_julia(data: dict, out: Path = OUT) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    pieces = [
        "# Generated by scripts.numerics.witness.prime_defect_export_julia_reduced",
        "# Do not edit by hand; rerun the exporter instead.",
        _julia_vector("centers", data["centers"]),
        _julia_matrix("coeff_map", data["coeff_map"]),
        _julia_matrix("S", data["S"]),
        _julia_matrix("Q", data["Q"]),
        _julia_matrix("square", data["square"]),
        _julia_matrix("G", data["G"]),
        _julia_vector("active_vec", data["active_vec"]),
        _julia_vector("schur_eigs", data["schur_eigs"]),
        "ACTIVE23 = (",
        f"    ncenters = {data['ncenters']},",
        f"    half_width = {_julia_float(data['half_width'])},",
        "    centers = centers,",
        f"    edge = {_julia_float(data['edge'])},",
        f"    cell_lo = {_julia_float(data['cell_lo'])},",
        f"    cell_hi = {_julia_float(data['cell_hi'])},",
        f"    logn = {_julia_float(data['logn'])},",
        f"    w_min = {_julia_float(data['w_min'])},",
        f"    w_max = {_julia_float(data['w_max'])},",
        f"    w_atom = {_julia_float(data['w_atom'])},",
        f"    atom_weight = {_julia_float(data['atom_weight'])},",
        f"    smooth_mass = {_julia_float(data['smooth_mass'])},",
        f"    old_dim = {data['old_dim']},",
        f"    shell_dim = {data['shell_dim']},",
        "    coeff_map = coeff_map,",
        "    S = S,",
        "    Q = Q,",
        "    square = square,",
        "    G = G,",
        "    active_vec = active_vec,",
        "    schur_eigs = schur_eigs,",
        ")",
        "",
    ]
    out.write_text("\n".join(pieces))


def main() -> None:
    data = reduced_data()
    write_julia(data)
    print(f"wrote {OUT}")
    print(f"shell_dim={data['shell_dim']} schur_eigs={data['schur_eigs']}")


if __name__ == "__main__":
    main()
