def nilpotents_on_rank1_are_zero():
    """Every nilpotent N on C^1 is N=0 (a 1x1 matrix [[a]] is nilpotent <=> a=0).  Returns the verdict
    and the (trivial) monodromy filtration M(0) on C^1: a SINGLE weight, NO symmetric split."""
    # the generic 1x1 endomorphism is [[a]]; nilpotent (a^k=0) <=> a=0
