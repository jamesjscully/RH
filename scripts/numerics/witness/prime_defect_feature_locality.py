"""Locality tests for feature-cone fits of the passive defect kernel.

``prime_defect_feature_fit.py`` showed that Euler atom features fit the finite
defect kernel much better than simple moment features.  This script asks
whether that fit is local to the newly entering support shell or whether it
needs the whole active Euler history.

For each nested extension H_L subset H_R we fit

    Delta = I - K^* K

using nonnegative cones generated by:

  * moments: I, |u|, u^2;
  * new atoms: n with log n in [L, R);
  * old atoms: n with log n < L;
  * all atoms: n with log n < R.

The atom features are the positive/negative spectral parts of D-normalized
prime-atom compressions on the shell, as in the previous feature-fit witness.

Run:
    python3 -m scripts.numerics.witness.prime_defect_feature_locality
"""
from __future__ import annotations

import math

import numpy as np

from .prime_carleson_flow import _sym
from .prime_defect_feature_fit import _fit, _invsqrt_spd, _moment_feature
from .prime_nested_cone import _orthogonal_shell, margin_at
from .prime_shell_coupling_bound import REFINEMENTS, ambient_for, cached_point

FOCUS_EDGES = (
    (1.72, 1.88),
    (1.88, 2.10),
    (2.30, 2.52),
    (2.76, 3.00),
    (3.00, 3.24),
)


def _atom_parts_by_age(ambient, kind: str, left_gmax: float, right_gmax: float,
                       shell: np.ndarray, D_invsqrt: np.ndarray,
                       age: str) -> list[tuple[str, np.ndarray]]:
    rows = []
    for n, atom in ambient.atoms[kind].items():
        logn = math.log(n)
        if logn >= right_gmax:
            continue
        if age == "new" and not (left_gmax <= logn < right_gmax):
            continue
        if age == "old" and not (logn < left_gmax):
            continue
        if age not in {"new", "old", "all"}:
            raise ValueError(f"unknown atom age: {age}")

        B = _sym(D_invsqrt @ (shell.T @ atom @ shell) @ D_invsqrt)
        eigs, vecs = np.linalg.eigh(B)
        pos = np.zeros_like(B)
        neg = np.zeros_like(B)
        for eig, vec in zip(eigs, vecs.T):
            outer = np.outer(vec, vec)
            if eig > 1e-12:
                pos += eig * outer
            elif eig < -1e-12:
                neg += -eig * outer
        if np.linalg.norm(pos) > 1e-12:
            rows.append((f"n{n}+", _sym(pos)))
        if np.linalg.norm(neg) > 1e-12:
            rows.append((f"n{n}-", _sym(neg)))
    return rows


def locality_row(kind: str, ncenters: int, half_width: float,
                 left_gmax: float, right_gmax: float) -> dict:
    ambient = ambient_for(ncenters, half_width)
    left = cached_point(ambient, kind, left_gmax)
    right = cached_point(ambient, kind, right_gmax)
    shell = _orthogonal_shell(ambient, left["basis"], right["basis"])
    B = np.column_stack([left["basis"], shell])
    old_dim = left["basis"].shape[1]
    M = margin_at(ambient, kind, right_gmax)
    block = _sym(B.T @ M @ B)
    A = _sym(block[:old_dim, :old_dim])
    C = block[:old_dim, old_dim:]
    D = _sym(block[old_dim:, old_dim:])
    A_invsqrt = _invsqrt_spd(A)
    D_invsqrt = _invsqrt_spd(D)
    new_ns = sorted(set(right["active_ns"]) - set(left["active_ns"]))

    if A_invsqrt is None or D_invsqrt is None:
        return {
            "kind": kind,
            "basis": f"n{ncenters}/hw{half_width:.2f}",
            "left_gmax": left_gmax,
            "right_gmax": right_gmax,
            "new_ns": new_ns,
            "valid": False,
            "shell_dim": int(shell.shape[1]),
            "A_min": float(np.linalg.eigvalsh(A)[0]) if A.size else float("nan"),
            "D_min": float(np.linalg.eigvalsh(D)[0]) if D.size else float("nan"),
        }

    K = A_invsqrt @ C @ D_invsqrt
    delta = _sym(np.eye(K.shape[1]) - K.T @ K)
    moment_features = [
        ("I", np.eye(delta.shape[0])),
        ("|u|", _moment_feature(ambient, shell, D_invsqrt, 1)),
        ("u2", _moment_feature(ambient, shell, D_invsqrt, 2)),
    ]
    new_features = _atom_parts_by_age(ambient, kind, left_gmax, right_gmax, shell, D_invsqrt, "new")
    old_features = _atom_parts_by_age(ambient, kind, left_gmax, right_gmax, shell, D_invsqrt, "old")
    all_features = _atom_parts_by_age(ambient, kind, left_gmax, right_gmax, shell, D_invsqrt, "all")
    return {
        "kind": kind,
        "basis": f"n{ncenters}/hw{half_width:.2f}",
        "left_gmax": left_gmax,
        "right_gmax": right_gmax,
        "new_ns": new_ns,
        "valid": True,
        "shell_dim": int(shell.shape[1]),
        "delta_min": float(np.linalg.eigvalsh(delta)[0]),
        "rho": float(1.0 - np.linalg.eigvalsh(delta)[0]),
        "mom": _fit(delta, moment_features),
        "new": _fit(delta, new_features),
        "old": _fit(delta, old_features),
        "all": _fit(delta, all_features),
        "mom_new": _fit(delta, moment_features + new_features),
        "mom_old": _fit(delta, moment_features + old_features),
        "mom_all": _fit(delta, moment_features + all_features),
        "n_new_features": len(new_features),
        "n_old_features": len(old_features),
        "n_all_features": len(all_features),
    }


def all_rows(kind: str) -> list[dict]:
    return [
        locality_row(kind, ncenters, half_width, left, right)
        for ncenters, half_width in REFINEMENTS
        for left, right in FOCUS_EDGES
    ]


def _new_n_text(row: dict) -> str:
    return ",".join(str(n) for n in row["new_ns"]) or "none"


def _print_rows(rows: list[dict], label: str) -> None:
    print(f"\n[1] Atom-feature locality for {label}")
    print("      edge        basis       new n       dim dmin    mom   new   old   all   mom+new mom+old mom+all")
    for row in rows:
        if not row.get("valid"):
            print(f"      {row['left_gmax']:.2f}->{row['right_gmax']:.2f}  "
                  f"{row['basis']:<10}  "
                  f"{_new_n_text(row):<10} "
                  f"{row['shell_dim']:2d} invalid A/D "
                  f"Amin={row['A_min']:+.2e} Dmin={row['D_min']:+.2e}")
            continue
        print(f"      {row['left_gmax']:.2f}->{row['right_gmax']:.2f}  "
              f"{row['basis']:<10}  "
              f"{_new_n_text(row):<10} "
              f"{row['shell_dim']:2d}  "
              f"{row['delta_min']:+.3f}  "
              f"{row['mom']['rel']:.3f} "
              f"{row['new']['rel']:.3f} "
              f"{row['old']['rel']:.3f} "
              f"{row['all']['rel']:.3f}    "
              f"{row['mom_new']['rel']:.3f}   "
              f"{row['mom_old']['rel']:.3f}   "
              f"{row['mom_all']['rel']:.3f}")


def _print_summary(rows: list[dict]) -> None:
    print("\n[2] Locality residual summary")
    print("      kind   rows  mom    new    old    all    mom+new mom+old mom+all")
    for kind in ("zeta", "DH"):
        group = [row for row in rows if row["kind"] == kind and row.get("valid")]
        if not group:
            continue
        keys = ("mom", "new", "old", "all", "mom_new", "mom_old", "mom_all")
        means = {key: float(np.nanmean([row[key]["rel"] for row in group])) for key in keys}
        print(f"      {kind:<5}  "
              f"{len(group):2d}    "
              f"{means['mom']:.3f}  "
              f"{means['new']:.3f}  "
              f"{means['old']:.3f}  "
              f"{means['all']:.3f}    "
              f"{means['mom_new']:.3f}   "
              f"{means['mom_old']:.3f}   "
              f"{means['mom_all']:.3f}")


def summary() -> dict:
    print("=" * 78)
    print("Locality of Euler features in passive defect-kernel fits")
    print("=" * 78)
    zeta_rows = all_rows("zeta")
    dh_rows = all_rows("DH")
    _print_rows(zeta_rows, "zeta")
    _print_rows(dh_rows, "DH")
    _print_summary(zeta_rows + dh_rows)

    print("\nInterpretation:")
    print("  * New atoms alone do not explain the zeta defect kernel.")
    print("  * Old active atoms often fit as well as all atoms, so Delta is a history")
    print("    kernel for the whole Euler Toeplitz flow, not a local jump kernel.")
    print("  * The next proof target should be a cumulative positive kernel identity")
    print("    along the nested Sonin chain.")
    return {
        "zeta_rows": zeta_rows,
        "DH_rows": dh_rows,
    }


if __name__ == "__main__":
    summary()
