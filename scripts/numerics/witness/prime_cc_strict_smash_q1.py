def binom_int(n, p):
    """C(n, p) = n(n-1)...(n-p+1)/p! as an exact integer, any integer n."""
    num = 1
    for i in range(p):
        num *= (n - i)
    return num // math.factorial(p)


def total(k, l, a, b, S):
    return sum(a[i] * b[j] for (i, j) in S)


def col_sums(k, l, a, b, S):
    A = [0] * l
    for (i, j) in S:
        A[j] += a[i]
    return A


def row_sums(k, l, a, b, S):
    B = [0] * k
    for (i, j) in S:
        B[i] += b[j]
    return B


def Phi(k, l, a, b, S, p):
    A = col_sums(k, l, a, b, S)
    return sum((b[j] ** p) * binom_int(A[j], p) for j in range(l)) % p


def PhiP(k, l, a, b, S, p):  # Phi'_p
    B = row_sums(k, l, a, b, S)
    return sum((a[i] ** p) * binom_int(B[i], p) for i in range(k)) % p


def inv_tuple(obj):
    k, l, a, b, S = obj
    return (total(k, l, a, b, S),
            Phi(k, l, a, b, S, 2), Phi(k, l, a, b, S, 3),
            PhiP(k, l, a, b, S, 2), PhiP(k, l, a, b, S, 3))


def push(vec, phi, n_target):
    """Pushforward of an integer vector along a pointed map
    phi: k_+ -> n_+ given as a tuple phi[i] in {0..n_target} (0 = basept):
    (phi_* v)_{i'} = Sum_{phi(i)=i'} v_i."""
    out = [0] * n_target
    for i, t in enumerate(phi):
        if t != 0:
            out[t - 1] += vec[i]
    return tuple(out)


def pull_S_a(Sp, phi, k, l):
    """RIGHT-object S for an A-move: S = {(i,j): phi(i)!=0,
    (phi(i)-1, j) in S'}."""
    return frozenset((i, j) for i in range(k) for j in range(l)
                     if phi[i] != 0 and (phi[i] - 1, j) in Sp)


def pull_S_b(Sp, psi, k, l):
    return frozenset((i, j) for i in range(k) for j in range(l)
                     if psi[j] != 0 and (i, psi[j] - 1) in Sp)


