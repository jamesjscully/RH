"""History ablation for the passive defect-kernel atom features.

The locality test showed that old active Euler atoms fit the finite defect
kernel much better than newly entering atoms.  This script asks whether the
kernel has short memory or genuinely uses a longer Euler history.

For each shell, fit

    Delta = I - K^* K

with nonnegative cones generated by old atom features from:

  * the earliest old atoms;
  * the most recent old atoms before the current support edge;
  * all old atoms;
  * all active atoms.

Run:
    python3 -m scripts.numerics.witness.prime_defect_history_ablation
"""
from __future__ import annotations

import math

import numpy as np

from .prime_carleson_flow import _sym
from .prime_defect_feature_fit import _fit, _invsqrt_spd
from .prime_nested_cone import _orthogonal_shell, margin_at
from .prime_shell_coupling_bound import REFINEMENTS, ambient_for, cached_point

FOCUS_EDGES = (
    (1.72, 1.88),
    (1.88, 2.10),
    (2.30, 2.52),
    (2.76, 3.00),
    (3.00, 3.24),
)
MEMORY_SIZES = (1, 2, 3, 5)


def _atom_parts_for_ns(ambient, kind: str, shell: np.ndarray,
                       D_invsqrt: np.ndarray, ns: list[int]) -> list[tuple[str, np.ndarray]]:
    rows = []
    for n in ns:
        atom = ambient.atoms[kind].get(n)
        if atom is None:
            continue
        B = _sym(D_invsqrt @ (shell.T @ atom @ shell) @ D_invsqrt)
        eigs, vecs = np.linalg.eigh(B)
        pos = np.zeros_like(B)
        neg = np.zeros_like(B)
        for eig, vec in zip(eigs, vecs.T):
            outer = np.outer(vec, vec)
            if eig > 1e-12:
                pos += eig * outer
            elif eig < -1e-12:
                neg += -eig * outer
        if np.linalg.norm(pos) > 1e-12:
            rows.append((f"n{n}+", _sym(pos)))
        if np.linalg.norm(neg) > 1e-12:
            rows.append((f"n{n}-", _sym(neg)))
    return rows


def ablation_row(kind: str, ncenters: int, half_width: float,
                 left_gmax: float, right_gmax: float) -> dict:
    ambient = ambient_for(ncenters, half_width)
    left = cached_point(ambient, kind, left_gmax)
    right = cached_point(ambient, kind, right_gmax)
    shell = _orthogonal_shell(ambient, left["basis"], right["basis"])
    B = np.column_stack([left["basis"], shell])
    old_dim = left["basis"].shape[1]
    M = margin_at(ambient, kind, right_gmax)
    block = _sym(B.T @ M @ B)
    A = _sym(block[:old_dim, :old_dim])
    C = block[:old_dim, old_dim:]
    D = _sym(block[old_dim:, old_dim:])
    A_invsqrt = _invsqrt_spd(A)
    D_invsqrt = _invsqrt_spd(D)
    old_ns = sorted(n for n in ambient.atoms[kind] if math.log(n) < left_gmax)
    new_ns = sorted(n for n in ambient.atoms[kind] if left_gmax <= math.log(n) < right_gmax)
    active_ns = sorted(n for n in ambient.atoms[kind] if math.log(n) < right_gmax)

    if A_invsqrt is None or D_invsqrt is None:
        return {
            "kind": kind,
            "basis": f"n{ncenters}/hw{half_width:.2f}",
            "left_gmax": left_gmax,
            "right_gmax": right_gmax,
            "old_ns": old_ns,
            "new_ns": new_ns,
            "valid": False,
            "shell_dim": int(shell.shape[1]),
            "A_min": float(np.linalg.eigvalsh(A)[0]) if A.size else float("nan"),
            "D_min": float(np.linalg.eigvalsh(D)[0]) if D.size else float("nan"),
        }

    K = A_invsqrt @ C @ D_invsqrt
    delta = _sym(np.eye(K.shape[1]) - K.T @ K)
    fits = {
        "all_old": _fit(delta, _atom_parts_for_ns(ambient, kind, shell, D_invsqrt, old_ns)),
        "all_active": _fit(delta, _atom_parts_for_ns(ambient, kind, shell, D_invsqrt, active_ns)),
        "new": _fit(delta, _atom_parts_for_ns(ambient, kind, shell, D_invsqrt, new_ns)),
    }
    for k in MEMORY_SIZES:
        fits[f"recent{k}"] = _fit(
            delta,
            _atom_parts_for_ns(ambient, kind, shell, D_invsqrt, old_ns[-k:]),
        )
        fits[f"early{k}"] = _fit(
            delta,
            _atom_parts_for_ns(ambient, kind, shell, D_invsqrt, old_ns[:k]),
        )
    return {
        "kind": kind,
        "basis": f"n{ncenters}/hw{half_width:.2f}",
        "left_gmax": left_gmax,
        "right_gmax": right_gmax,
        "old_ns": old_ns,
        "new_ns": new_ns,
        "valid": True,
        "shell_dim": int(shell.shape[1]),
        "delta_min": float(np.linalg.eigvalsh(delta)[0]),
        "rho": float(1.0 - np.linalg.eigvalsh(delta)[0]),
        "fits": fits,
    }


def all_rows(kind: str) -> list[dict]:
    return [
        ablation_row(kind, ncenters, half_width, left, right)
        for ncenters, half_width in REFINEMENTS
        for left, right in FOCUS_EDGES
    ]


def _new_n_text(row: dict) -> str:
    return ",".join(str(n) for n in row["new_ns"]) or "none"


def _fit_rel(row: dict, key: str) -> float:
    return row["fits"][key]["rel"]


def _print_rows(rows: list[dict], label: str) -> None:
    print(f"\n[1] Euler-history ablation for {label}")
    print("      edge        basis       new n       dim dmin    new   r1    r3    r5    e3    all-old all-active")
    for row in rows:
        if not row.get("valid"):
            print(f"      {row['left_gmax']:.2f}->{row['right_gmax']:.2f}  "
                  f"{row['basis']:<10}  "
                  f"{_new_n_text(row):<10} "
                  f"{row['shell_dim']:2d} invalid A/D "
                  f"Amin={row['A_min']:+.2e} Dmin={row['D_min']:+.2e}")
            continue
        print(f"      {row['left_gmax']:.2f}->{row['right_gmax']:.2f}  "
              f"{row['basis']:<10}  "
              f"{_new_n_text(row):<10} "
              f"{row['shell_dim']:2d}  "
              f"{row['delta_min']:+.3f}  "
              f"{_fit_rel(row, 'new'):.3f} "
              f"{_fit_rel(row, 'recent1'):.3f} "
              f"{_fit_rel(row, 'recent3'):.3f} "
              f"{_fit_rel(row, 'recent5'):.3f} "
              f"{_fit_rel(row, 'early3'):.3f} "
              f"{_fit_rel(row, 'all_old'):.3f}   "
              f"{_fit_rel(row, 'all_active'):.3f}")


def _finite_mean(values: list[float]) -> float:
    vals = [v for v in values if np.isfinite(v)]
    return float(np.mean(vals)) if vals else float("nan")


def _print_summary(rows: list[dict]) -> None:
    print("\n[2] History-ablation residual summary")
    print("      kind   rows  new    recent1 recent3 recent5 early3  all-old all-active")
    for kind in ("zeta", "DH"):
        group = [row for row in rows if row["kind"] == kind and row.get("valid")]
        if not group:
            continue
        keys = ("new", "recent1", "recent3", "recent5", "early3", "all_old", "all_active")
        means = {key: _finite_mean([_fit_rel(row, key) for row in group]) for key in keys}
        print(f"      {kind:<5}  "
              f"{len(group):2d}    "
              f"{means['new']:.3f}  "
              f"{means['recent1']:.3f}   "
              f"{means['recent3']:.3f}   "
              f"{means['recent5']:.3f}   "
              f"{means['early3']:.3f}   "
              f"{means['all_old']:.3f}   "
              f"{means['all_active']:.3f}")


def summary() -> dict:
    print("=" * 78)
    print("Euler-history ablation for passive defect-kernel fits")
    print("=" * 78)
    zeta_rows = all_rows("zeta")
    dh_rows = all_rows("DH")
    _print_rows(zeta_rows, "zeta")
    _print_rows(dh_rows, "DH")
    _print_summary(zeta_rows + dh_rows)

    print("\nInterpretation:")
    print("  * Very short memory is not enough on the harder zeta shells.")
    print("  * Recent old atoms improve the fit, but the full old active history is")
    print("    consistently better; all-active adds only a small further improvement.")
    print("  * The analytic target is a cumulative transfer/kernel identity, not a")
    print("    local-in-L point interaction.")
    return {
        "zeta_rows": zeta_rows,
        "DH_rows": dh_rows,
    }


if __name__ == "__main__":
    summary()
