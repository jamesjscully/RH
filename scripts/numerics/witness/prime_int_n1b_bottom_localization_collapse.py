"""N1-b' bottom localization witness: inverting the DMP bottom class collapses.

Docs 139-141 leave R1 open only as a different carrier.  The nearest repair
attempt is to force the missing Lin/Weyl-Tate Laurent line by localizing the
same DMP bottom class y from TCR(F_2;2)^{phi Z/2}.

At the DMP support level y has degree -1 and y^2=0 because pi_-2 vanishes
(doc 140).  Localizing a unital ring at a nilpotent element makes the zero
ring: the multiplicative set contains y^2=0.  Equivalently, adjoining a
two-sided inverse y^{-1} to y^2=0 gives 1=0.

So bottom-class localization cannot create F_2[t^{+-1}].  Any nonzero full
line must introduce a new non-nilpotent generator and is therefore a genuinely
different carrier, subject again to the DD.4 and DH/Epstein guards.

Run:
    python3 -m scripts.numerics.witness.prime_int_n1b_bottom_localization_collapse
"""

failures = []


def gate(name, ok, detail=""):
    print(("PASS" if ok else "FAIL"), name, detail)
    if not ok:
        failures.append(name)


def dmp_dim(deg):
    """F_2-dimension of pi_deg TCR(F_2;2)^{phi Z/2} from DMP C/E."""
    if deg == -1:
        return 1
    if deg >= 0:
        return 1
    return 0


def lin_dim(_deg):
    """F_2-dimension of the Laurent line F_2[t^{+-1}] in every degree."""
    return 1


bottom_exists = dmp_dim(-1) == 1
bottom_square_zero = dmp_dim(-2) == 0

gate(
    "BLC1 DMP bottom class exists in degree -1",
    bottom_exists,
    f"dim[-1]={dmp_dim(-1)}",
)

gate(
    "BLC2 DMP bottom class is square-zero by support",
    bottom_exists and bottom_square_zero,
    "(-1)+(-1)=-2 and dim[-2]=0",
)

gate(
    "BLC3 Lin/Weyl-Tate line has a nonzero degree -2 square",
    lin_dim(-1) == 1 and lin_dim(-2) == 1,
    f"Lin[-1]={lin_dim(-1)} Lin[-2]={lin_dim(-2)}",
)


# Localization at the multiplicative set S={1,y,y^2,...}.  Since y^2=0,
# S contains 0, so S^{-1}R is the zero ring.
multiplicative_set_contains_zero = bottom_square_zero
localized_ring_zero = multiplicative_set_contains_zero
gate(
    "BLC4 localization at the DMP bottom class is the zero ring",
    localized_ring_zero,
    "the set {1,y,y^2,...} contains y^2=0",
)


# Equivalent inverse-adjunction check.  If a two-sided inverse v of y exists,
# then y = y^2 v = 0, and then 1 = v y = 0.
inverse_forces_y_zero = bottom_square_zero
inverse_forces_one_zero = inverse_forces_y_zero and bottom_exists
gate(
    "BLC5 adjoining an inverse to the bottom class forces 1=0",
    inverse_forces_one_zero,
    "y^2=0 and y*v=1 imply y=0 and hence 1=0",
)


# A zero localized carrier cannot realize a Laurent line.  The only possible
# escape is to add a new generator not generated by the DMP bottom class.
gate(
    "BLC6 zero localized carrier cannot supply F_2[t^{+-1}]",
    localized_ring_zero and lin_dim(-3) == 1 and lin_dim(3) == 1,
    "localized dimensions all collapse, while Lin has one class in every degree",
)


same_bottom_repair_possible = not localized_ring_zero
new_generator_required = localized_ring_zero
gate(
    "BLC7 any surviving full line requires a new non-nilpotent generator",
    (not same_bottom_repair_possible) and new_generator_required,
    "same-bottom localization is closed; a nonzero full line is a different carrier",
)


if failures:
    print("\nFAILURES:")
    for failure in failures:
        print(" -", failure)
    raise SystemExit(1)

print("\nALL PASS (BLC1-BLC7)")
print(
    "VERDICT: localizing or formally inverting the DMP bottom class y collapses "
    "the carrier, because y is square-zero.  It cannot manufacture the "
    "Lin/Weyl-Tate Laurent line.  Any nonzero full-line repair must introduce "
    "a new non-nilpotent generator and must be tested as a genuinely different "
    "carrier."
)
