def valuation_depth(n: int, p: int) -> int | None:
    depth = 0
    while n > 1 and n % p == 0:
        n //= p
        depth += 1
    if n != 1:
        return None
    return depth


def odd_base_depth(n: int, odd_base: int = 3, p: int = 2) -> int | None:
    if n % odd_base != 0:
        return None
    return valuation_depth(n // odd_base, p)


