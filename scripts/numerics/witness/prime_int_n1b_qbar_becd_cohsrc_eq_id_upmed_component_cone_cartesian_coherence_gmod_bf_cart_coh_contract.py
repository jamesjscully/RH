def reasons(data) -> list[str]:
    out = [label for key, label in REQUIRED if not data[key]]
    if set(data["finite_index"]) != FINITE_INDEX:
        out.append("finite_index_not_exact")
    if data["finite_index_cardinality"] != len(FINITE_INDEX):
        out.append("finite_index_cardinality_wrong")
    if set(BOUNDARY_FIBER_COHERENCE_CELLS) - set(data["coherence_cells"]):
        out.append("required_boundary_fiber_coherence_cells_missing")
    if REQUIRED_COHERENT_CARTESIAN_FIBER_EDGES - set(data["coherent_cartesian_fiber_edges"]):
        out.append("required_coherent_cartesian_fiber_edges_missing")
    if NATURALITY_PATHS - set(data["naturality_paths"]):
        out.append("required_multiplier_paths_missing")
    out.extend(label for key, label in BANNED if data[key])
    return out


