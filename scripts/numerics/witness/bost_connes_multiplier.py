    # discreteness: consecutive integer gap is 1 (a marked GAP), vs R_{>0}^x continuum (gap 0)
    srt = sorted(set(ns))
    gaps = [srt[i + 1] - srt[i] for i in range(len(srt) - 1)]
    discrete_gap = min(gaps) if gaps else 0
    return law, discrete_gap


