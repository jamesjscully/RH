def bc_semigroup_is_discrete_multiplicative(ns):
    """The BC isometries mu_n (n in N^x) satisfy mu_m mu_n = mu_{mn}: a DISCRETE MULTIPLICATIVE
    semigroup.  We verify the semigroup law on the index (m*n is the product index) and that the index
    set is DISCRETE (gaps between consecutive integers = 1, a genuine spectral gap, unlike R_{>0}^x).
    Returns (multiplicative_law_holds, discrete_gap)."""
    # the semigroup law mu_m mu_n = mu_{mn} is realized on indices by m*n:
