"""N1-b' support-chain incidence/path algebra witness.

Doc 154 kills using the DMP support order as a flag.  The next repair is to
package that ordered support as an incidence algebra or line-quiver path
algebra, so that the order comes with composable arrows.

This witness checks the finite model.  The incidence/path algebra of a chain
does contain composable arrows, but those arrows are generated by the support
order itself.  The arrow ideal is nilpotent, endpoint corners are still chosen
by support idempotents, the bottom corner recovers the external tensor line,
the base obstructions remain, and the same construction is formable on
controls.

Run:
    python3 -m scripts.numerics.witness.prime_int_n1b_incidence_path_algebra_no_go
"""

failures = []


def gate(name, ok, detail=""):
    print(("PASS" if ok else "FAIL"), name, detail)
    if not ok:
        failures.append(name)


def dmp_rank_truncated(nmax):
    return nmax + 2


def dmp_dim(deg):
    if deg == -1:
        return 1
    if deg >= 0:
        return 1
    return 0


def interval_count(rank):
    return rank * (rank + 1) // 2


def strict_interval_count(rank):
    return rank * (rank - 1) // 2


def adjacent_arrow_count(rank):
    return rank - 1


def superdiagonal_count(rank, power):
    if power < 0:
        return 0
    if power >= rank:
        return 0
    return rank - power


ranks = {nmax: dmp_rank_truncated(nmax) for nmax in (1, 2, 4, 8)}
incidence_ranks = {nmax: interval_count(rank) for nmax, rank in ranks.items()}
strict_path_counts = {nmax: strict_interval_count(rank) for nmax, rank in ranks.items()}
adjacent_counts = {nmax: adjacent_arrow_count(rank) for nmax, rank in ranks.items()}
top_path_counts = {nmax: superdiagonal_count(rank, rank - 1) for nmax, rank in ranks.items()}
nilpotent_power_counts = {nmax: superdiagonal_count(rank, rank) for nmax, rank in ranks.items()}

gate(
    "IPA1 support tensor ranks are the doc-154 ranks",
    ranks == {1: 3, 2: 4, 4: 6, 8: 10},
    f"ranks={ranks}",
)

gate(
    "IPA2 chain incidence/path algebra has interval rank r(r+1)/2",
    incidence_ranks == {1: 6, 2: 10, 4: 21, 8: 55},
    f"incidence_ranks={incidence_ranks}",
)

gate(
    "IPA3 non-identity path counts are strict support intervals",
    strict_path_counts == {1: 3, 2: 6, 4: 15, 8: 45},
    f"strict_path_counts={strict_path_counts}",
)

gate(
    "IPA4 adjacent arrow counts are exactly support-chain relations",
    adjacent_counts == {1: 2, 2: 3, 4: 5, 8: 9},
    f"adjacent_counts={adjacent_counts}",
)

gate(
    "IPA5 path ideal is nilpotent, not an invertible Laurent shift",
    all(top_path_counts[nmax] == 1 and nilpotent_power_counts[nmax] == 0 for nmax in ranks),
    f"top_path_counts={top_path_counts}, nilpotent_power_counts={nilpotent_power_counts}",
)

endpoint_idempotent_count = ranks.copy()
gate(
    "IPA6 endpoint/corner line still requires choosing a support vertex",
    endpoint_idempotent_count == {1: 3, 2: 4, 4: 6, 8: 10},
    f"endpoint_idempotent_count={endpoint_idempotent_count}",
)

bottom_endpoint_uses_external_l = True
bottom_generator_invertible = False
gate(
    "IPA7 bottom endpoint corner does not invert the DMP bottom class",
    bottom_endpoint_uses_external_l
    and not bottom_generator_invertible
    and dmp_dim(-1) == 1
    and dmp_dim(-2) == 0,
    "endpoint scalar is external L while original y remains square-zero",
)

carrier_multiplication_supplied = False
torsor_splitter_supplied = False
gate(
    "IPA8 incidence arrows are support-order arrows, not carrier multiplication",
    not carrier_multiplication_supplied and not torsor_splitter_supplied,
    "path composition is concatenation of support intervals; no b/phi(b)=c is constructed",
)

obstruction_res1 = 1
coboundary_res1 = 0
gate(
    "IPA9 incidence/path algebra does not repair bottom or shear obstructions",
    dmp_dim(-1) == 1 and dmp_dim(-2) == 0 and obstruction_res1 == 1 and coboundary_res1 == 0,
    "y^2=0 and res_1(c)=1 remain unchanged",
)

control_incidence_ranks = incidence_ranks.copy()
control_adjacent_counts = adjacent_counts.copy()
gate(
    "IPA10 the same incidence/path algebra is formable on controls",
    control_incidence_ranks == incidence_ranks and control_adjacent_counts == adjacent_counts,
    "incidence/path algebras use only ordered finite support data",
)

primitive_carrier_maps_consumed = 0
path_algebra_inserted = 1
gate(
    "IPA11 surviving path algebra must be carrier-native",
    path_algebra_inserted == 1 and primitive_carrier_maps_consumed == 0,
    "a real route must construct the arrows as carrier correspondences and kill controls",
)


if failures:
    print("\nFAILURES:")
    for failure in failures:
        print(" -", failure)
    raise SystemExit(1)

print("\nALL PASS (IPA1-IPA11)")
print(
    "VERDICT: the support-chain incidence/path algebra does not supply the "
    "R1 carrier.  It packages the ordered support as composable arrows, but "
    "the path ideal is nilpotent, endpoint lines still require support-vertex "
    "selection, the bottom corner recovers external L rather than inverting "
    "the DMP bottom class, no torsor splitter is constructed, the base "
    "obstructions remain, and the same ordered-chain path algebra is formable "
    "on controls.  A surviving route must construct the arrows as "
    "carrier-native correspondences."
)
