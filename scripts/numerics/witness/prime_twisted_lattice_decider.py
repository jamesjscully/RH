def vp(n: int, p: int) -> int:
    if n == 0:
        return 10**9  # sentinel: infinite valuation
    v = 0
    while n % p == 0:
        n //= p
        v += 1
    return v


def nu_factorial(n: int, p: int) -> int:
    v, q = 0, p
    while q <= n:
        v += n // q
        q *= p
    return v


def q_poly(n: int, p: int, a: int, b: int) -> int:
    """q_n(a,b) = prod_{j=0}^{n-1} (b - j(p-1)a)."""
    out = 1
    for j in range(n):
        out *= b - j * (p - 1) * a
    return out


