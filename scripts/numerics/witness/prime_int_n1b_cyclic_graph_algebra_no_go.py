r"""Cyclic graph algebra no-go.

After doc 216, the next repair is to take the algebra generated by the graph,
Z[F], equip it with the trace/Rosati form F^dag=qF^{-1}, and declare that to
be the square correspondence algebra.  This still does not construct
End(S^2/Z): the cyclic algebra is only the z-component of correspondences,
it does not determine the NS triples (d1,z,d2), and its trace form detects
off-circle failure rather than constructing positivity.

Run:
    python3 -m scripts.numerics.witness.prime_int_n1b_cyclic_graph_algebra_no_go
"""

from __future__ import annotations

import numpy as np

from scripts.numerics.witness.ns_diagonal_representability import (
    diagonal,
    frobenius,
    frobenius_graph,
    ns_intersection,
    rosati,
    weil_pairing,
)


failures: list[str] = []


def gate(name: str, ok: bool, detail: str = "") -> None:
    print(("PASS" if ok else "FAIL"), name, detail)
    if not ok:
        failures.append(name)


def rosati_trace_gram(F: np.ndarray, E: np.ndarray) -> np.ndarray:
    basis = [np.eye(F.shape[0]), F]
    return np.array([[np.trace(A @ rosati(B, E)).real for B in basis] for A in basis])


def positive_definite(M: np.ndarray) -> bool:
    return bool(np.all(np.linalg.eigvalsh((M + M.T) / 2.0) > 1e-9))


def indefinite(M: np.ndarray) -> bool:
    eig = np.linalg.eigvalsh((M + M.T) / 2.0)
    return bool(np.min(eig) < -1e-9 and np.max(eig) > 1e-9)


def qsim_defect(F: np.ndarray, E: np.ndarray, q: float) -> float:
    return float(np.linalg.norm(F.T @ E @ F - q * E))


def cyclic_span_rank(F: np.ndarray) -> int:
    powers = [np.eye(F.shape[0]), F]
    flattened = np.stack([P.reshape(-1) for P in powers], axis=1)
    return int(np.linalg.matrix_rank(flattened, tol=1e-10))


# CGA1: in the genuine finite-field case the cyclic trace form has the
# expected positive sign. This is an anchor, not a construction over Z.
q_true = 7
F_true = frobenius(q_true, 1)
E_true = weil_pairing(F_true, q_true)
G_true = rosati_trace_gram(F_true, E_true)
true_relation = float(np.linalg.norm(rosati(F_true, E_true) - q_true * np.linalg.inv(F_true)))

gate(
    "CGA1 genuine FF cyclic graph algebra has positive Rosati trace form",
    cyclic_span_rank(F_true) == 2
    and true_relation < 1e-12
    and positive_definite(G_true)
    and abs(np.linalg.det(G_true) - 27.0) < 1e-9,
    "Gram=%s, det=%.3f" % (G_true.astype(int).tolist(), np.linalg.det(G_true)),
)


# CGA2: for the off-circle integral q-similitude graph, the same cyclic
# algebra and involution exist, but the trace form is indefinite.
q_off = 2
F_off = frobenius(q_off, 3)
E_off = weil_pairing(F_off, q_off)
G_off = rosati_trace_gram(F_off, E_off)
off_relation = float(np.linalg.norm(rosati(F_off, E_off) - q_off * np.linalg.inv(F_off)))
off_qsim = qsim_defect(F_off, E_off, q_off)
off_eigs = np.linalg.eigvalsh((G_off + G_off.T) / 2.0)

gate(
    "CGA2 cyclic trace form detects off-circle failure but does not repair it",
    cyclic_span_rank(F_off) == 2
    and off_relation < 1e-12
    and off_qsim < 1e-12
    and indefinite(G_off),
    "Gram=%s, eig=%s, relation=%.1e"
    % (G_off.astype(int).tolist(), [round(float(x), 6) for x in off_eigs], off_relation),
)


# CGA3: if the graph algebra is allowed to retune the degree to its own norm,
# positivity can hold, but the prescribed external q is gone.
external_q = 7
self_q = 5
F_self = frobenius(self_q, 2)
E_self = weil_pairing(F_self, self_q)
G_self = rosati_trace_gram(F_self, E_self)
self_qsim = qsim_defect(F_self, E_self, self_q)
external_qsim = qsim_defect(F_self, E_self, external_q)

gate(
    "CGA3 cyclic self-degree positivity does not choose the external base size",
    positive_definite(G_self)
    and self_qsim < 1e-12
    and external_qsim > 1e-3
    and self_q != external_q,
    "self_q=%d, external_q=%d, self_qsim=%.1e, external_qsim=%.3f"
    % (self_q, external_q, self_qsim, external_qsim),
)


# CGA4: the cyclic algebra only sees z. The NS square needs triples
# (d1,z,d2). Same z-component, different fiber degrees, different
# intersections.
D_true = diagonal(F_true)
D_fake_same_z = (0, np.eye(2), 0)
Gamma = frobenius_graph(F_true, q_true, 1)
z_components_equal = np.linalg.norm(D_true[1] - D_fake_same_z[1]) < 1e-12
true_intersection = ns_intersection(D_true, Gamma)
fake_intersection = ns_intersection(D_fake_same_z, Gamma)

gate(
    "CGA4 z-algebra does not determine NS triples or diagonal intersections",
    z_components_equal and abs(true_intersection - fake_intersection) > 1e-9,
    "same z=Id, Delta.Gamma=%.3f, fake.Gamma=%.3f"
    % (true_intersection, fake_intersection),
)


# CGA5: cyclic graph algebras are formable on untyped controls.
control_q = 2
control = np.array([[1.0, 1.0], [1.0, 3.0]])
control_E = weil_pairing(control, control_q)
control_gram = rosati_trace_gram(control, control_E)
control_has_euler_product = False
control_has_satake = False
control_has_rep_ns = False
control_has_square_intersections = False
control_has_positive_rosati = False

gate(
    "CGA5 cyclic graph algebra is formable on controls",
    cyclic_span_rank(control) == 2
    and qsim_defect(control, control_E, control_q) < 1e-12
    and not control_has_euler_product
    and not control_has_satake
    and not control_has_rep_ns
    and not control_has_square_intersections
    and not control_has_positive_rosati,
    "control Gram=%s, no Euler/Satake/rep_NS/Rosati"
    % [[round(float(x), 3) for x in row] for row in control_gram.tolist()],
)


# CGA6: construction audit.
zeta_rep_ns_constructed = False
zeta_ns_triples_constructed = False
zeta_diagonal_constructed = False
zeta_fiber_degrees_constructed = False
zeta_off_diagonal_intersections_constructed = False
zeta_positive_rosati_constructed = False
zeta_control_death_constructed = False
zeta_dd4_weight_ge_1_constructed = False

